# BATCH TRANSACTION SCORING
# ============================================================

@app.post(
    "/score/batch",
    response_model=List[MLScoreResponse]
)
def batch_score_endpoint(
    txns: List[MLScoreRequest]
):

    if len(txns) > 100:
        raise HTTPException(
            status_code=413,
            detail="Batch size exceeds maximum of 100 transactions"
        )

    return [
        score_transaction_endpoint(
            txn
        )
        for txn in txns
    ]