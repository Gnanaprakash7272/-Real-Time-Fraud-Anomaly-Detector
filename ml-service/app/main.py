@app.get("/model-metrics")
def get_model_metrics():

    # evaluation_metrics.json is generated
    # by train_model.py after real model evaluation.

    metrics_path = os.path.join(
        MODELS_DIR,
        "evaluation_metrics.json"
    )


    # --------------------------------------------------------
    # Check metrics file exists
    # --------------------------------------------------------

    if not os.path.exists(
        metrics_path
    ):

        raise HTTPException(
            status_code=404,
            detail=(
                "Model evaluation metrics not found. "
                "Run train_model.py first."
            )
        )


    # --------------------------------------------------------
    # Read real evaluation metrics
    # --------------------------------------------------------

    try:

        with open(
            metrics_path,
            "r",
            encoding="utf-8"
        ) as file:

            metrics = json.load(
                file
            )


        return metrics


    except Exception as e:

        raise HTTPException(
            status_code=500,
            detail=(
                "Unable to load model metrics: "
                f"{str(e)}"
            )
        )


