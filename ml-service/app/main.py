@app.post(
    "/score",
    response_model=MLScoreResponse
)
def score_transaction_endpoint(
    txn: MLScoreRequest
):

    # --------------------------------------------------------
    # Verify required models
    # --------------------------------------------------------

    if (
        gb_model is None
        or iso_forest is None
    ):

        raise HTTPException(
            status_code=500,
            detail=(
                "ML models not initialized"
            )
        )


    # --------------------------------------------------------
    # Convert request into model features
    # --------------------------------------------------------

    txn_dict = txn.model_dump()


    X_df = transform_transaction(
        txn_dict,
        feature_cols
    )


    # --------------------------------------------------------
    # Ensemble scoring
    # --------------------------------------------------------

    (
        gb_prob,
        iso_score,
        is_anomaly,
        ae_mse,
        blended_score,
        risk_level

    ) = score_ensemble(

        X_df,
        gb_model,
        iso_forest,
        autoencoder,
        ae_scaler
    )


    # --------------------------------------------------------
    # Rule-based explainability
    # --------------------------------------------------------

    rule_reasons = (
        generate_rule_reasons(
            X_df,
            txn_dict
        )
    )


    # --------------------------------------------------------
    # SHAP explainability
    # --------------------------------------------------------

    shap_dict, shap_reasons = (
        compute_shap_explanations(
            gb_model,
            X_df
        )
    )


    # Remove duplicate reasons while
    # preserving original ordering.

    all_reasons = list(
        dict.fromkeys(
            rule_reasons
            + shap_reasons
        )
    )


    # --------------------------------------------------------
    # API response
    # --------------------------------------------------------

    ae_threshold = ae_scaler["threshold"] if ae_scaler else 0.05
    ae_status = "UNAVAILABLE" if autoencoder is None else "NORMAL"

    if autoencoder is not None and ae_mse > ae_threshold:
        ae_status = "HIGH"

    return MLScoreResponse(

        transaction_id=(
            txn.transaction_id
        ),

        gradient_boost_probability=round(
            gb_prob,
            4
        ),

        gradient_boost_risk_percent=round(
            gb_prob * 100,
            2
        ),

        isolation_forest_score=round(
            iso_score,
            4
        ),

        isolation_forest_anomaly=(
            is_anomaly
        ),

        autoencoder_mse=round(
            ae_mse,
            6
        ),

        autoencoder_status=ae_status,

        ensemble_risk_score=round(
            blended_score,
            4
        ),

        risk_level=(
            risk_level
        ),

        top_reasons=(
            all_reasons
        ),

        shap_values=(
            shap_dict
        )
    )


