# LOAD TRAINED MODELS
# ============================================================

def load_models():

    # --------------------------------------------------------
    # Gradient Boosting
    # --------------------------------------------------------

    gb_path = os.path.join(
        MODELS_DIR,
        "gb_model.pkl"
    )

    # Support the actual filename generated by train_model.py
    if not os.path.exists(gb_path):

        gb_path = os.path.join(
            MODELS_DIR,
            "gradient_boost.pkl"
        )


    # --------------------------------------------------------
    # Isolation Forest
    # --------------------------------------------------------

    iso_path = os.path.join(
        MODELS_DIR,
        "isolation_forest.pkl"
    )


    # --------------------------------------------------------
    # Feature columns
    # --------------------------------------------------------

    cols_path = os.path.join(
        MODELS_DIR,
        "feature_cols.pkl"
    )


    gb = (
        joblib.load(gb_path)
        if os.path.exists(gb_path)
        else None
    )


    iso = (
        joblib.load(iso_path)
        if os.path.exists(iso_path)
        else None
    )


    cols = (
        joblib.load(cols_path)
        if os.path.exists(cols_path)
        else [
            "amount",
            "oldbalanceOrg",
            "newbalanceOrig",
            "oldbalanceDest",
            "newbalanceDest",
            "balanceDiffOrig",
            "balanceDiffDest",
            "origBalanceZero",
            "destBalanceZero",
            "type_CASH_IN",
            "type_CASH_OUT",
            "type_DEBIT",
            "type_PAYMENT",
            "type_TRANSFER"
        ]
    )


    # --------------------------------------------------------
    # Autoencoder
    # --------------------------------------------------------

    ae = None
    ae_scaler = None   # dict: {min, range, threshold}

    ae_path = os.path.join(
        MODELS_DIR,
        "autoencoder.pt"
    )

    if os.path.exists(ae_path):

        try:

            import torch
            import torch.nn as nn

            checkpoint = torch.load(ae_path, map_location="cpu")

            # New format: state_dict dict saved by train_autoencoder.py
            if isinstance(checkpoint, dict) and "model_state" in checkpoint:

                input_dim = checkpoint["input_dim"]

                class _AE(nn.Module):
                    def __init__(self):
                        super().__init__()
                        self.encoder = nn.Sequential(
                            nn.Linear(input_dim, 16), nn.ReLU(),
                            nn.Linear(16, 8),          nn.ReLU(),
                            nn.Linear(8, 4),           nn.ReLU()
                        )
                        self.decoder = nn.Sequential(
                            nn.Linear(4, 8),           nn.ReLU(),
                            nn.Linear(8, 16),          nn.ReLU(),
                            nn.Linear(16, input_dim),  nn.Sigmoid()
                        )
                    def forward(self, x):
                        return self.decoder(self.encoder(x))

                _model = _AE()
                _model.load_state_dict(checkpoint["model_state"])
                _model.eval()
                ae = _model

                ae_scaler = {
                    "min":       np.array(checkpoint["feat_min"],   dtype=np.float32),
                    "range":     np.array(checkpoint["feat_range"], dtype=np.float32),
                    "threshold": float(checkpoint.get("threshold", 0.05))
                }

            else:
                # Legacy format: full model object
                ae = checkpoint

        except Exception as e:
            print(f"[WARN] Could not load autoencoder: {e}")
            ae = None
            ae_scaler = None

    return (
        gb,
        iso,
        cols,
        ae,
        ae_scaler
    )


# Load models once when FastAPI starts

gb_model, iso_forest, feature_cols, autoencoder, ae_scaler = (
    load_models()
)

if gb_model is not None:
    init_shap_explainer(gb_model)


